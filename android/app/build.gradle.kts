val configuredApiUrl: String? =
  (findProperty("biddriveApiBaseUrl") as String?)?.takeIf { it.isNotBlank() }
    ?: System.getenv("BIDDRIVE_API_BASE_URL")?.takeIf { it.isNotBlank() }
val defaultApiUrl = "https://biddrive-api.onrender.com/api/"
fun normalise(url: String): String {
  val trimmed = url.trim().trimEnd('/')
  val withApi = if (trimmed.endsWith("/api")) trimmed else "$trimmed/api"
  return "$withApi/"
}

